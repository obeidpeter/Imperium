// Writes docs/realtime-encounters.md: each battle's real-time map scale chosen
// by travel time (build brief §3.2), with the route, the 0.38 turns and the
// real-time rounds it was calibrated on. Each battle is built as the campaign
// builds it: the command campaign's expanded field (ten tiles wide where the
// chapter's theme is wide), its operation phases, and a row for each decision
// that changes the field. Development only; `--check` fails when the committed
// document is out of date.
import {readFile,writeFile} from 'node:fs/promises';
import * as G from '../src/core/game.js';
import {calibrate,layoutFor} from '../src/core/realtime/campaign-encounter.js';
import {createBattle} from '../src/core/battle.js';
import {initializeExpanded} from '../src/core/expanded-campaign.js';
import {CHAPTERS} from '../src/data/campaign.js';
import {BATTLE_SCENARIOS} from '../src/data/encounters.js';
import {BATTLE_OPERATIONS} from '../src/data/battle-operations.js';
import {MISSION_OPERATIONS} from '../src/data/mission-operations.js';

// The decisions that change a battle's field or its protected party (battle.js).
const VARIANTS={'ch2-marsh':['ch2',['carry','leave']],'ch6-wells':['ch6',['save','obey']],'ch8-ferry':['ch8',['families','soldiers']]};
const tile=p=>`${p.x+1}${String.fromCharCode(65+p.y)}`;
const rows=[];
for(const ch of CHAPTERS)for(const [index,data]of ch.encounters.entries()){
  if(data.kind!=='battle')continue;
  const [decision,options]=VARIANTS[data.id]??[null,[null]];
  // New Game's campaigns play release 7's missions; a battle they re-author also gets a row as earlier campaigns play it.
  for(const missions of MISSION_OPERATIONS[data.id]!==BATTLE_OPERATIONS[data.id]?[true,false]:[true])for(const option of options){
    const s=G.newGame('Calibration',275,{featureEdition:35,progression:true,missions});s.chapter=ch.id;s.encounterIndex=index;
    // The command campaign's departure switches the expanded field on (command-campaign.js).
    Object.assign(s,{featureEdition:31,reforms:[],fieldRecords:[]});if(decision)s.decisions[decision]=option;
    s.encounter=createBattle(s,data,{});initializeExpanded(s);
    const e=s.encounter,c=calibrate(e),layout=layoutFor(e.width,e.height,c.k),w=layout.kx.reduce((a,b)=>a+b,0)*2.5,h=layout.ky.reduce((a,b)=>a+b,0)*2.5;
    rows.push(`| ${ch.id} | \`${data.id}\`${option?` (${option})`:''}${missions?'':' (before the missions)'} | ${BATTLE_SCENARIOS[data.id]?.mode??e.mission.mode} | ${e.width} × ${e.height} | ${c.k.toFixed(3)} | ${(c.k*2.5).toFixed(2)} m | ${w} × ${h} m | `+
      `${c.route?`${tile(c.route.from)} → ${tile(c.route.to)}`:'—'} | ${c.turns??'—'} | ${c.rounds!==null?c.rounds.toFixed(2):'—'} | ${c.error!==null?`${(c.error*100).toFixed(1)}%`:'—'} | ${e.turnLimit} |`);
  }
}
const text=`# Real-time encounter scales

Generated by \`node scripts/realtime-encounters.mjs\` from the rules; do not edit by hand.

Build brief §3.2 asks for each encounter's map scale to be chosen by travel time, not by converting tiles to metres mechanically: the rounds needed to cross the encounter's route at its default pace must stay within ±10% of the 0.38 turn count. This is what keeps evacuation travel time preserved.

- **Field.** Each battle is built as the campaign builds it: the command campaign's expanded field (ten 0.38 tiles wide in Chapters V, VIII, IX and XII, with the side gate and the damaged footbridge), its operation phases, and one row for each decision that changes the field or the protected party (Chapter II's wounded Lucan, Chapter VI's Varro behind his breastwork, Chapter VIII's second column). New Game's campaigns play release 7's missions; the six battles they re-author have a second row, *before the missions*, as campaigns begun earlier play them.
- **Route.** An evacuation uses the protected column's road from its start to the extraction marker. Every other battle uses the soldier's road to the farthest objective of any operation phase.
- **0.38 turns.** The route's movement cost in 0.38 (marsh costs two) at two tiles a turn.
- **Real-time rounds.** The same route found by the real-time navigation on the upsampled map, walked at 1.6 m/s with marsh ×0.6 and fords ×0.5, in rounds of ten seconds.
- **Scale.** Each 0.38 tile becomes a block of 2.5 m tiles, *k* a side on average: columns and rows take ⌊k⌋ or ⌈k⌉ tiles, spread evenly. *k* runs from 2 to 4.5 in eighths; the scale nearest 3 within ±6% is taken, otherwise the closest to parity.
- **Ranges and radii** use the guide's metres, never the tile scale. A 0.38 "within one tile" (objectives, holding a place) becomes one tile's width at this scale.
- **Deadline.** The battle's deadline in rounds: the 0.38 turn limit on Standard, its operation's extra turns included. A walled 0.38 tile with no wall beside it (Varro's shelter, Chapter VII's fortification) becomes a breastwork round its block, open at the rear, rather than solid ground.

| Ch | Encounter | Mode | 0.38 tiles | k | Tile | Field | Route | 0.38 turns | Rounds | Error | Deadline |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;
const target=new URL('../docs/realtime-encounters.md',import.meta.url);
if(process.argv.includes('--check')){
  const current=await readFile(target,'utf8').catch(()=>'');if(current!==text){console.error('docs/realtime-encounters.md is out of date. Run node scripts/realtime-encounters.mjs.');process.exit(1);}
  console.log('docs/realtime-encounters.md is current.');
}else{await writeFile(target,text);console.log(`Wrote ${rows.length} rows.`);}
