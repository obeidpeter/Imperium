// render of the game, with no text, as Steam asks; the library logo is the name alone, on transparency, 1280 wide.
const dark=a=>`rgba(16,10,6,${a})`;
const fromLeft=(reach,strong,mid)=>({from:[0,0],to:[reach,0],stops:[[0,dark(strong)],[.6,dark(mid)],[1,dark(0)]]});
const fromBottom=(strong,mid)=>({from:[0,.45],to:[0,1],stops:[[0,dark(0)],[.55,dark(mid)],[1,dark(strong)]]});
// The Horizon camera drawn in to four fifths of its distance: past the near ground's slab, onto the gate and the formations.
