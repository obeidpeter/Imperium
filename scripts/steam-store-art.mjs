// node scripts/steam-store-art.mjs [--hero]: drafts of the store's and the library's images for Steamworks (the Steam
// plan, S4), made from the game's own art with nothing generated. The capsules, the page background and the library's
// capsule and header are drawn from the key painting (assets/scenes/frontier-oath.webp, the landing page's), with the
// name set in Cinzel (SIL Open Font License 1.1; art-source/fonts/cinzel/, a development file the game does not ship)
// and the emblem of icon.svg. The library hero is a render of the game's own 3D stage at its full size: the finale
// before the Aurelian Walls, from the legally reached checkpoint in tests/fixtures/campaign-3d.json (generated by
// node scripts/campaign-3d-fixtures.mjs, which npm test runs). --hero renders it again; without it, the hero already
// in desktop/steam/store-art/ is kept. Each image is written at the exact pixel size Steamworks asks for, with a review
// sheet in tests/visual-results/steam-store-art/ (not committed). The sizes are Steam's as reported; check them in
// Steamworks before uploading (docs/steam-store-art.md).
// Needs Playwright like the other review scripts (PLAYWRIGHT_MODULE). Draws in headless Chromium's 2D canvas; the
// hero renders in its software WebGL, which takes several minutes.
