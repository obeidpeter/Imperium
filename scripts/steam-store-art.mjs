/** How far an image enlarges the painting: above about 1.5 it softens. The hero is rendered at its own size. */
export const enlargement=a=>a.crop?Math.max(a.width/a.crop[2],a.height/a.crop[3]):a.render?1:0;
export const fileName=a=>`${a.id}.${a.png?'png':'jpg'}`;

// In the page: draws every painted image, the logo and the review sheet, as data URLs. The hero comes in rendered.
function drawArt(specs,{font,painting,name,hero}){
  return (async()=>{
    const face=new FontFace('Cinzel',Uint8Array.from(atob(font),c=>c.charCodeAt(0)).buffer,{weight:'400 900'});await face.load();document.fonts.add(face);
    const load=async src=>{const img=new Image();img.src=src;await img.decode();return img;};
    const img=await load(painting),heroImg=hero?await load(hero):null;
    const STAR=new Path2D('M96 34l13 36 48-17-21 37-28 10 15 32-27-14-27 14 15-32-28-10-21-37 48 17z');
    const canvas=(w,h)=>{const c=document.createElementNS('http://www.w3.org/1999/xhtml','canvas');c.width=w;c.height=h;return c;};
    // The name: the title fitted to a width, a bronze rule with the emblem, and the subtitle. Returns its height.
    const lettering=(x,{cx,top,width,subtitle=true,align='center'})=>{
      const set=s=>{x.font=`700 ${s}px Cinzel`;x.letterSpacing=`${s*0.06}px`;};
      set(100);const size=100*width/x.measureText(name.title).width;set(size);
      const tw=x.measureText(name.title).width,left=align==='left'?cx:cx-tw/2,base=top+size*0.78;
      x.save();x.shadowColor='rgba(12,7,4,.85)';x.shadowBlur=size*0.22;x.shadowOffsetY=size*0.03;
      const g=x.createLinearGradient(0,top,0,top+size*0.8);g.addColorStop(0,'#fff4d8');g.addColorStop(.55,'#f0dcaa');g.addColorStop(1,'#c99a56');
      x.fillStyle=g;x.fillText(name.title,left+size*0.03,base);x.restore();
      x.save();set(size);x.lineWidth=Math.max(1,size*0.012);x.strokeStyle='rgba(40,22,12,.55)';x.strokeText(name.title,left+size*0.03,base);x.restore();
      if(!subtitle)return base+size*0.25-top;
      const dy=base+size*0.2,mid=left+tw/2,s=size*0.2/126;
      x.save();x.strokeStyle='#c9a564';x.lineWidth=Math.max(1,size*0.014);x.shadowColor='rgba(12,7,4,.8)';x.shadowBlur=size*0.08;
      x.beginPath();x.moveTo(left+tw*0.1,dy);x.lineTo(mid-size*0.22,dy);x.moveTo(mid+size*0.22,dy);x.lineTo(left+tw*0.9,dy);x.stroke();
      x.translate(mid-96*s,dy-83*s);x.scale(s,s);x.fillStyle='#e5d1a4';x.fill(STAR);x.restore();
      const ss=size*0.165;x.save();x.font=`600 ${ss}px Cinzel`;x.letterSpacing=`${ss*0.3}px`;x.fillStyle='#f1e3bf';x.textAlign='center';
      x.shadowColor='rgba(12,7,4,.9)';x.shadowBlur=ss*0.6;x.fillText(name.subtitle,mid+ss*0.15,dy+ss*1.55);x.restore();
      return dy+ss*1.55+ss*0.5-top;
    };
    const images=[];
    for(const a of specs){
      let c;
      if(a.render){c=canvas(a.width,a.height);if(heroImg)c.getContext('2d').drawImage(heroImg,0,0);images.push({data:null,width:a.width,height:a.height,canvas:c});continue;}
      if(a.height===null){
        // The logo alone: drawn on a tall transparent canvas, then cut to its own height, with room for its shadow.
        const tall=canvas(a.width,720),x=tall.getContext('2d'),pad=a.width*0.04;
        const h=lettering(x,{cx:a.name.x*a.width,top:pad,width:a.name.width*a.width,subtitle:a.name.subtitle!==false});
        c=canvas(a.width,Math.min(720,Math.ceil(h+pad*2)));c.getContext('2d').drawImage(tall,0,0);
      }else{
        c=canvas(a.width,a.height);const x=c.getContext('2d');x.imageSmoothingQuality='high';
        const [sx,sy,sw,sh]=a.crop;x.drawImage(img,sx,sy,sw,sh,0,0,a.width,a.height);
        if(a.filter){const t=canvas(a.width,a.height),tx=t.getContext('2d');tx.filter=a.filter;tx.drawImage(c,0,0);x.clearRect(0,0,a.width,a.height);x.drawImage(t,0,0);}
        for(const s of a.shade??[]){
          const g=s.radial?x.createRadialGradient(s.radial[0]*a.width,s.radial[1]*a.height,0,s.radial[0]*a.width,s.radial[1]*a.height,s.radial[2]*a.width)
            :x.createLinearGradient(s.from[0]*a.width,s.from[1]*a.height,s.to[0]*a.width,s.to[1]*a.height);
          for(const [o,col] of s.stops)g.addColorStop(o,col);x.fillStyle=g;x.fillRect(0,0,a.width,a.height);
        }
        if(a.name)lettering(x,{cx:a.name.x*a.width,top:a.name.y*a.height,width:a.name.width*a.width,subtitle:a.name.subtitle!==false,align:a.name.align});
      }
      images.push({data:c.toDataURL(a.png?'image/png':'image/jpeg',0.92),width:c.width,height:c.height,canvas:c});
    }
    // The review sheet: every image over a mid grey (so the logo's transparency shows), the hero across the top with
    // the logo over it as Steam places it by default, the rest at most 520 pixels tall.
    const W=1840,gap=24,heroIndex=specs.findIndex(a=>a.render),logoIndex=specs.findIndex(a=>a.height===null);
    const heroW=W-gap*2,heroH=heroW*specs[heroIndex].height/specs[heroIndex].width;let y=gap+heroH+46,x=gap,lineH=0;const placed=[];
    for(const [i,a] of specs.entries()){if(i===heroIndex)continue;const im=images[i],s=Math.min(1,520/im.height,(W-gap*2)/im.width),w=im.width*s,h=im.height*s;
      if(x+w>W-gap){y+=lineH+46;x=gap;lineH=0;}placed.push({i,x,y,w,h});x+=w+gap;lineH=Math.max(lineH,h);}
    const sheet=canvas(W,y+lineH+60),sx=sheet.getContext('2d');sx.fillStyle='#4a4741';sx.fillRect(0,0,sheet.width,sheet.height);
    const caption=(i,px,py)=>{sx.fillStyle='#f3ead6';sx.font='15px sans-serif';sx.fillText(`${specs[i].slot} · ${images[i].width} × ${images[i].height}`,px,py);};
    sx.drawImage(images[heroIndex].canvas,gap,gap,heroW,heroH);
    const logo=images[logoIndex].canvas,lw=heroW*0.3;sx.drawImage(logo,gap+heroW*0.04,gap+heroH*0.55,lw,lw*logo.height/logo.width);caption(heroIndex,gap,gap+heroH+20);
    for(const p of placed){sx.drawImage(images[p.i].canvas,p.x,p.y,p.w,p.h);caption(p.i,p.x,p.y+p.h+20);}
    return {images:images.map(({data,width,height})=>({data,width,height})),sheet:sheet.toDataURL('image/png')};
  })();
}

// In the page: the finale's stage from its legally reached checkpoint, framed by the Horizon camera, labels hidden.
function renderStage({scene,quality,camera,width,height}){
  return (async()=>{
    const Game=await import('./src/core/game.js'),{createBattleStageController}=await import('./src/ui/battle-stage-controller.js');
    const response=await fetch('./tests/fixtures/campaign-3d.json');if(!response.ok)throw Error('Generate the checkpoints first: node scripts/campaign-3d-fixtures.mjs');
    const fixture=(await response.json()).scenes.find(s=>s.id===scene);if(!fixture)throw Error(`No checkpoint for ${scene}`);
    document.body.innerHTML='';document.body.style.margin='0';
    const style=document.createElement('style');style.textContent='.world-labels{display:none!important}';document.head.append(style);
    const host=document.createElement('div');host.style.cssText=`position:fixed;left:0;top:0;width:${width}px;height:${height}px;overflow:hidden;background:#000`;
    const canvas=document.createElement('canvas');canvas.style.cssText='display:block;width:100%;height:100%';host.append(canvas);document.body.append(host);
    let error=null;const controller=createBattleStageController({onError:e=>{error=String(e);}});
    const state=Game.deserialize(Game.serialize(fixture.state));
    controller.mount(canvas,{encounter:state.encounter,chapter:state.chapter,rank:state.rank,selected:null,targets:[],target:null,grid:false,
      quality,figureStyle:'sculpted',reducedMotion:true,audio:false,audioVolume:0,paused:false});
    const frames=n=>new Promise(done=>{let k=0;const step=()=>{if(++k>=n)done();else requestAnimationFrame(step);};requestAnimationFrame(step);});
    const until=async(test,ms)=>{const start=performance.now();while(!test()){if(error)throw Error(error);if(performance.now()-start>ms)throw Error('The stage did not finish building.');await frames(1);}};
    await until(()=>controller.stage,300000);const stage=controller.stage;await until(()=>stage.stats().samples>=2,600000);
    if(camera.view==='horizon')stage.horizon();
    stage.orbit.yaw+=camera.yaw;if(camera.pitch!==null)stage.orbit.pitch=camera.pitch;stage.orbit.distance*=camera.distance;
    stage.baseTarget.x+=camera.target[0];stage.baseTarget.y+=camera.target[1];stage.baseTarget.z+=camera.target[2];
    await frames(12);if(error)throw Error(error);
    const stats=stage.stats();return {cameraView:stats.cameraView,quality:stats.quality,orbit:{...stage.orbit},serializedUnchanged:Game.serialize(state)===Game.serialize(fixture.state)};
  })();
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  let pw;for(const p of [process.env.PLAYWRIGHT_MODULE,'playwright'].filter(Boolean))try{const m=await import(isAbsolute(p)?pathToFileURL(p).href:p);pw=m.chromium?m:m.default;break;}catch{}
  assert.ok(pw?.chromium,'Set PLAYWRIGHT_MODULE to an installed Playwright.');
  const heroSpec=STORE_ART.find(a=>a.render),heroFile=join(out,fileName(heroSpec));
  const rerender=process.argv.includes('--hero')||!(await access(heroFile).then(()=>true,()=>false));
  const font=(await readFile(join(root,FONT))).toString('base64');
  const server=http.createServer((req,res)=>serveRequest(req,res,root));await new Promise(done=>server.listen(0,'127.0.0.1',done));
  const base=`http://127.0.0.1:${server.address().port}`;
  const browser=await pw.chromium.launch({executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH||undefined,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
  try{
    await mkdir(out,{recursive:true});
    if(rerender){
      const page=await browser.newPage({viewport:{width:heroSpec.width,height:heroSpec.height},deviceScaleFactor:1});
      const errors=[];page.on('pageerror',e=>errors.push(String(e)));
      await page.goto(`${base}/tests/campaign-3d-browser.html`);
      const info=await page.evaluate(`(${renderStage})(${JSON.stringify({...heroSpec.render,width:heroSpec.width,height:heroSpec.height})})`);
      assert.equal(info.quality,heroSpec.render.quality,'the hero renders at its quality');assert.ok(info.serializedUnchanged,'rendering leaves the checkpoint unchanged');
      assert.deepEqual(errors,[],'the stage renders without page errors');
      await writeFile(heroFile,await page.screenshot({clip:{x:0,y:0,width:heroSpec.width,height:heroSpec.height},type:'jpeg',quality:92,timeout:600000}));
      await page.close();console.log(`Rendered the library hero: ${heroSpec.render.scene}, ${info.cameraView} camera, ${info.quality} quality.`);
    }
    const page=await browser.newPage();await page.goto(`${base}/icon.svg`);
    const hero=`data:image/jpeg;base64,${(await readFile(heroFile)).toString('base64')}`;
    const drawn=await page.evaluate(`(${drawArt})(${JSON.stringify(STORE_ART)},${JSON.stringify({font,painting:PAINTING.src,name:NAME,hero})})`);
    const bytes=d=>Buffer.from(d.slice(d.indexOf(',')+1),'base64');
    for(const [i,a] of STORE_ART.entries()){
      if(a.render)continue;const {width,height,data}=drawn.images[i];
      assert.equal(width,a.width,a.id);if(a.height)assert.equal(height,a.height,a.id);await writeFile(join(out,fileName(a)),bytes(data));
    }
    await mkdir(review,{recursive:true});await writeFile(join(review,'review-sheet.png'),bytes(drawn.sheet));
    console.log(`Wrote ${STORE_ART.length} images to desktop/steam/store-art/ and a review sheet to tests/visual-results/steam-store-art/.`);
  }finally{await browser.close();server.close();}
}
