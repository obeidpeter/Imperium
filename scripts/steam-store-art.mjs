// What each image shows: the crop of the painting it is drawn from ([x, y, width, height] in the painting's pixels) or
// the render of the game it is made from, the shade laid over it so the name reads, and where the name goes (fractions
// of the image). The library hero carries no text, as Steam asks; the library logo is the name alone, on transparency.
const dark=a=>`rgba(16,10,6,${a})`;
const fromLeft=(reach,strong,mid)=>({from:[0,0],to:[reach,0],stops:[[0,dark(strong)],[.6,dark(mid)],[1,dark(0)]]});
const fromBottom=(strong,mid)=>({from:[0,.45],to:[0,1],stops:[[0,dark(0)],[.55,dark(mid)],[1,dark(strong)]]});
// The finale's stage from the Horizon camera, drawn in to four fifths of its distance: past the near ground's slab, onto
// the gate and the formations. A tall image moves the camera's target 10 metres along the stage's z axis, which centres
// the formations before the walls and keeps the slab out of a frame that shows more of the near ground.
export const RENDER_SCENE='ch12-confrontation';
const finale=(camera={})=>({scene:RENDER_SCENE,quality:'high',camera:{view:'horizon',distance:.8,yaw:0,pitch:null,target:[0,0,0],...camera}});
export const HERO=finale();
export const TALL=finale({target:[0,0,-10]});
