// node scripts/steam-store-art.mjs [--render]: drafts of the store's and the library's images for Steamworks (the Steam
// plan, S4), made from the game's own art with nothing generated. The header, small and main capsules, the page
// background and the library's header are drawn from the key painting (assets/scenes/frontier-oath.webp, the landing
// page's). The vertical capsule, the library's capsule and its hero are renders of the game's own 3D stage, each at its
// full size: the finale before the Aurelian Walls, from the legally reached checkpoint in tests/fixtures/campaign-3d.json
// (generated by node scripts/campaign-3d-fixtures.mjs, which npm test runs). The name is set in Cinzel (SIL Open Font
// License 1.1; art-source/fonts/cinzel/, a development file the game does not ship) with the emblem of icon.svg.
// --render renders the three again; without it, the renders already kept are used: the hero in desktop/steam/store-art/,
// and the two capsules' renders, before their name is drawn, in art-source/store-art/. Each image is written at the
// exact pixel size Steamworks asks for, with a review sheet in tests/visual-results/steam-store-art/ (not committed).
// The sizes are Steam's as reported; check them in Steamworks before uploading (docs/steam-store-art.md).
// Needs Playwright like the other review scripts (PLAYWRIGHT_MODULE). Draws in headless Chromium's 2D canvas; the renders
// use its software WebGL, which takes several minutes.
