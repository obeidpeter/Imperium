import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const sourceUrl=new URL('./character-sources/performance-v034.json',import.meta.url);
const outputUrl=new URL('../src/showcase/actor-performance-data.js',import.meta.url);
export function compileCharacterPerformance(source){
  if(source.version!==1||!source.clips||typeof source.method!=='string')throw new Error('Invalid performance source');
  const allowed=/^(hip[XYZ]|body[XYZ]|head[XY]|(?:left|right)(?:Arm[XYZ]|Elbow|Wrist|Foot(?:[XYZ]|Roll))|shieldTilt|skirt)$/;
  for(const [name,clip]of Object.entries(source.clips)){
    if(!/^[a-z]+$/.test(name)||!Array.isArray(clip.frames)||clip.frames.length<2)throw new Error(`Invalid clip ${name}`);
    let previous=-1;
    for(const [t,pose]of clip.frames){
      if(!Number.isFinite(t)||t<0||t>1||t<=previous)throw new Error(`Invalid time in ${name}`);previous=t;
      for(const [field,value]of Object.entries(pose)){
        const limit=field.startsWith('hip')?.12:/Foot[XYZ]$/.test(field)?.16:2.5;
        if(!allowed.test(field)||!Number.isFinite(value)||Math.abs(value)>limit)throw new Error(`Unbounded ${name}.${field}`);
      }
    }
    if(clip.frames[0][0]!==0||clip.frames.at(-1)[0]!==1)throw new Error(`Incomplete ${name}`);
    if(JSON.stringify(clip.frames[0][1])!==JSON.stringify(clip.frames.at(-1)[1]))throw new Error(`Discontinuous endpoints in ${name}`);
  }
  const hash=createHash('sha256').update(JSON.stringify(source)).digest('hex');
  return `// Generated by scripts/build-character-performance.mjs. Edit its JSON source.\n// ${source.method}\nexport const PERFORMANCE_SOURCE_HASH='${hash}';\nexport const PERFORMANCE_CLIPS=${JSON.stringify(source.clips)};\nfor(const clip of Object.values(PERFORMANCE_CLIPS)){for(const frame of clip.frames){Object.freeze(frame[1]);Object.freeze(frame);}Object.freeze(clip.frames);Object.freeze(clip);}Object.freeze(PERFORMANCE_CLIPS);\n`;
}
export function characterPerformanceMatches(source,exported){
  // Git's Windows checkout may use CRLF. Formatting is not a stale animation
  // export; the source digest already hashes parsed JSON rather than file bytes.
  return typeof exported==='string'&&exported.replaceAll('\r\n','\n')===compileCharacterPerformance(source);
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const source=JSON.parse(await readFile(sourceUrl,'utf8')),output=compileCharacterPerformance(source);
  if(process.argv.includes('--check')){
    if(!characterPerformanceMatches(source,await readFile(outputUrl,'utf8')))throw new Error('Character performance export is stale');
    console.log('Character performance source and runtime export match.');
  }else{await writeFile(outputUrl,output);console.log('Exported original character performance library.');}
}
