// Writes docs/tp-audit.md: the most training points each chapter can grant, by
// source and training path (build brief §3.5, test G33). Development only;
// `--check` fails when the committed document is out of date.
import {readFile,writeFile} from 'node:fs/promises';
import {tpAuditChapter,tpAuditTotal,AUDIT_PATHS} from '../src/core/tp-audit.js';
import {TP,COURSES} from '../src/data/soldier.js';
import {CHAPTERS} from '../src/data/campaign.js';

const roman=n=>['I','II','III','IV','V','VI','VII','VIII','IX','X','XI','XII'][n-1];
const rows=[],detail=[];
for(const ch of CHAPTERS){
  const by=Object.fromEntries(AUDIT_PATHS.map(p=>[p,tpAuditChapter(ch.id,p)])),a=by.legionary;
  rows.push(`| ${roman(ch.id)} | ${a.rows.reduce((n,r)=>n+r.objective,0)} | ${a.capabilities} | ${a.rows.reduce((n,r)=>n+r.kills,0)} | ${a.rows.reduce((n,r)=>n+r.commendations,0)} | `+
    `${AUDIT_PATHS.map(p=>by[p].errands).join(' / ')} | ${AUDIT_PATHS.map(p=>by[p].total).join(' / ')} | ${AUDIT_PATHS.map(p=>tpAuditTotal(ch.id,p)).join(' / ')} |`);
  for(const r of a.rows)detail.push(`| ${roman(ch.id)} | \`${r.id}\` | ${r.objective} | ${r.kills} | ${r.commendations} |`);
}
const courses=Object.values(COURSES).reduce((n,c)=>n+c.tp,0);
const text=`# Training-point audit

Generated by \`node scripts/tp-audit.mjs\` from the rules data; do not edit by hand.

There is no grinding: enemies never return and every errand is offered once, so the most training points (TP) a soldier can earn by each chapter is fixed. This table is that ceiling. A chronicle begun before 0.40 is granted the cumulative total to its chapter when it is first opened (build brief §3.17).

- **Objective:** each encounter's own TP when its result is recorded (default ${2}).
- **Capabilities:** ${TP.perCapability} TP for each capability the chapter requires, once.
- **Kills:** ${TP.perKill} TP for each enemy the soldier or a companion strikes down, at most ${TP.killCap} an encounter and never more than the enemies who take the field (waves included). The drill counts none.
- **Commendations:** a won fight can name keeping one's feet (1) and an ambush (1), and from Chapter III, when companions march, bringing every one home (2).
- **Errands:** each once; a training path's own errand only for its path. Columns read Legionary / Explorator / Librarius.

Raising an attribute costs ${TP.below20} TP below 20, ${TP.from20} from 20 and one more for every ten; every course together costs ${courses} TP.

| Chapter | Objectives | Capabilities | Kills (max) | Commendations (max) | Errands | Chapter total | Cumulative |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## By encounter

| Chapter | Encounter | Objective | Kills (max) | Commendations (max) |
| --- | --- | --- | --- | --- |
${detail.join('\n')}
`;
const target=new URL('../docs/tp-audit.md',import.meta.url);
if(process.argv.includes('--check')){
  const current=await readFile(target,'utf8').catch(()=>'');if(current!==text){console.error('docs/tp-audit.md is out of date. Run node scripts/tp-audit.mjs.');process.exit(1);}
  console.log('docs/tp-audit.md is current.');
}else{await writeFile(target,text);console.log(`Wrote the audit for ${CHAPTERS.length} chapters.`);}
