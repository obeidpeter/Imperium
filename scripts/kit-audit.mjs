// Writes docs/kit-audit.md: chapter by chapter, the most coin a soldier can have
// and the kit two reference soldiers wear, with their duels against the
// chapter's standard enemy and its champion (release 11). Development only;
// `--check` fails when the committed document is out of date or the audit
// finds a problem.
import {readFile,writeFile} from 'node:fs/promises';
import {KIT_AUDIT_CHAPTERS,kitAuditChapter,kitAuditProblems,itemScore} from '../src/core/kit-audit.js';
import {ITEMS} from '../src/data/items.js';
import {SMITH} from '../src/data/soldier.js';

const roman=n=>['I','II','III','IV','V','VI','VII','VIII','IX','X','XI','XII'][n-1];
const s=n=>n===null?'—':`${n} s`;
const rows=KIT_AUDIT_CHAPTERS.map(kitAuditChapter);
const table=rows.map(r=>`| ${roman(r.chapter)} | ${r.income} | ${r.issuedScore} | ${r.engagedScore} | ${s(r.duels.issued.enemy.kill)} / ${s(r.duels.issued.enemy.die)} | `+
  `${s(r.duels.engaged.enemy.kill)} / ${s(r.duels.engaged.enemy.die)} | ${r.champion?`${s(r.duels.issued.champion.kill)} / ${s(r.duels.issued.champion.die)}`:'—'} | `+
  `${r.champion?`${s(r.duels.engaged.champion.kill)} / ${s(r.duels.engaged.champion.die)}`:'—'} |`);
const bought=rows.map(r=>`| ${roman(r.chapter)} | ${r.bought.map(id=>ITEMS[id].name).join(', ')||'—'} |`);
const shelf=SMITH.map(({chapter,items})=>`| ${roman(chapter)} | ${items.map(id=>`${ITEMS[id].name} (${ITEMS[id].value} d, ${itemScore(id).toFixed(1)})`).join(', ')} |`);
const problems=kitAuditProblems();
const text=`# Kit audit

Generated by \`node scripts/kit-audit.mjs\` from the rules data; do not edit by hand.

There is no grinding for kit either: every container opens once, the champions fall once and the shelves are fixed, so the most coin a soldier can draw and the best kit he can wear by each chapter are fixed too (release 11 of the [worlds and gameplay plan](worlds-and-gameplay-plan.md)). Two reference soldiers of the Legionary's training are audited, as the calibration bot plays them (\`scripts/kit-policy.mjs\`):

- **Issued:** wears the best of what the army has issued him and spends half the training points the chapters before could have given (the [training-point audit](tp-audit.md)).
- **Engaged:** also has everything the containers and champions of the chapters before held, with this chapter's camp containers, buys the upgrades with the largest gain for their price within the coin ceiling, and spends all his training points.

**Coin ceiling:** his first purse, the pay of every chapter to this one, the donatives and errands so far, and the sale, at half value, of what the containers and champions held. **Score:** a weapon's mean damage per second of its swing, a shield's block, a belt's missiles and a garment's protection, less its Restriction (\`itemScore\` in \`src/core/kit-audit.js\`). **Duels:** the seconds he needs to fell one man, and to be felled by him, face to face, by the game's own blow forecast; the standard enemy is the chapter's infantry archetype at its tier, and the champion the chapter's first.

| Chapter | Coin ceiling | Issued kit | Engaged kit | Issued v. enemy (kill / die) | Engaged v. enemy | Issued v. champion | Engaged v. champion |
| --- | ---: | ---: | ---: | --- | --- | --- | --- |
${table.join('\n')}

## What the engaged soldier buys

| Chapter | Bought, by gain for the price |
| --- | --- |
${bought.join('\n')}

## The armourer's rack

Each piece's value in denarii and score; named pieces are never on it.

| From chapter | Pieces |
| --- | --- |
${shelf.join('\n')}

## Checks

${problems.length?problems.map(p=>`- ${p}`).join('\n'):'- Every piece on the armourer’s rack is affordable in the chapter it appears.\n- Every fine or named piece beats the best standard piece of its place and family on the shelves by then.\n- From Chapter II the engaged soldier’s kit scores at least a twentieth above the issued one’s.'}
`;
const target=new URL('../docs/kit-audit.md',import.meta.url);
if(process.argv.includes('--check')){
  const current=await readFile(target,'utf8').catch(()=>'');
  if(current!==text){console.error('docs/kit-audit.md is out of date. Run node scripts/kit-audit.mjs.');process.exit(1);}
  if(problems.length){console.error(problems.join('\n'));process.exit(1);}
  console.log('docs/kit-audit.md is current.');
}else{await writeFile(target,text);console.log(`Wrote the kit audit for ${rows.length} chapters${problems.length?`, with ${problems.length} problems`:''}.`);}
